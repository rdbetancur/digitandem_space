// Usage: node scripts/import-lunar-data.mjs path/to/ldem_16.tif
// NASA SVS CGI Moon Kit float32 TIFF: kilometers above the 1737.4 km sphere.
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
const bytes = readFileSync(process.argv[2]);
if (bytes.toString('ascii', 0, 2) !== 'II') throw Error('Expected little-endian TIFF');
const ifd = bytes.readUInt32LE(4), tags = new Map();
for (let i = 0; i < bytes.readUInt16LE(ifd); i++) {
  const at = ifd + 2 + i * 12;
  const tag = bytes.readUInt16LE(at), type = bytes.readUInt16LE(at + 2), count = bytes.readUInt32LE(at + 4);
  if (![256, 257, 258, 259, 273, 278, 339].includes(tag)) continue;
  const size = type === 3 ? 2 : 4;
  const start = count * size <= 4 ? at + 8 : bytes.readUInt32LE(at + 8);
  tags.set(tag, Array.from({ length: count }, (_, j) => size === 2 ? bytes.readUInt16LE(start + j * size) : bytes.readUInt32LE(start + j * size)));
}
const width = tags.get(256)[0], height = tags.get(257)[0], rows = tags.get(278)[0], offsets = tags.get(273);
if (width !== 5760 || height !== 2880 || tags.get(258)[0] !== 32 || tags.get(259)[0] !== 1 || tags.get(339)[0] !== 3) throw Error('Unexpected DEM format');
function pixel(x, y) {
  x = (x % width + width) % width; y = Math.max(0, Math.min(height - 1, y));
  return bytes.readFloatLE(offsets[Math.floor(y / rows)] + ((y % rows) * width + x) * 4) * 1000;
}
function elevation(lat, lon) {
  const x = (lon + 180) / 360 * width - 0.5, y = (90 - lat) / 180 * height - 0.5;
  const ix = Math.floor(x), iy = Math.floor(y), fx = x - ix, fy = y - iy;
  return (pixel(ix, iy) * (1 - fx) + pixel(ix + 1, iy) * fx) * (1 - fy)
    + (pixel(ix, iy + 1) * (1 - fx) + pixel(ix + 1, iy + 1) * fx) * fy;
}
const rad = Math.PI / 180, radius = 1737400;
// A polar great circle, starting at 49°S, 0°E; target at 89°S, 0°E.
const samples = Array.from({ length: 5760 }, (_, i) => {
  const a = (49 + i / 16) * rad;
  return Math.round(elevation(Math.asin(-Math.sin(a)) / rad, Math.cos(a) >= 0 ? 0 : -180));
});
const lat = -89 * rad, lon = 0, siteElevation = elevation(-89, 0);
const horizon = Array.from({ length: 72 }, (_, i) => {
  const az = i * 5 * rad;
  let max = 0;
  for (let distance = 2000; distance <= 100000; distance += 1000) {
    const arc = distance / radius;
    const la = Math.asin(Math.sin(lat) * Math.cos(arc) + Math.cos(lat) * Math.sin(arc) * Math.cos(az));
    const lo = lon + Math.atan2(Math.sin(az) * Math.sin(arc) * Math.cos(lat), Math.cos(arc) - Math.sin(lat) * Math.sin(la));
    max = Math.max(max, Math.atan2(elevation(la / rad, lo / rad) - siteElevation - distance * distance / (2 * radius), distance) / rad);
  }
  return Math.round(max * 1000) / 1000;
});
const meta = { source: 'https://svs.gsfc.nasa.gov/4720/', sha256: createHash('sha256').update(bytes).digest('hex'), pixelsPerDegree: 16, referenceRadiusM: radius, site: { lat: -89, lon: 0, elevationM: Math.round(siteElevation) } };
writeFileSync('src/sim/lunarData.ts', `// Generated by scripts/import-lunar-data.mjs; measured NASA LRO/LOLA elevations.\nexport const LUNAR_DATA = ${JSON.stringify(meta)} as const;\nexport const LUNAR_PROFILE: readonly number[] = ${JSON.stringify(samples)};\nexport const SITE_HORIZON: readonly number[] = ${JSON.stringify(horizon)};\n`);
console.log(meta, { minimum: Math.min(...samples), maximum: Math.max(...samples), horizon });
